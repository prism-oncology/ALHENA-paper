#!/bin/bash
#SBATCH --job-name=histost_rank_frontier      # job name
#SBATCH --output=./output/%x_%A_%a.out   # output file (%A = array job ID, %a = array task index)
#SBATCH --error=./output/%x_%A_%a.out    # error file
#SBATCH --constraint=h100                # request H100 GPUs (80 GB)
#SBATCH --nodes=1                        # number of nodes (per array task)
#SBATCH --ntasks=4                       # number of tasks (4 DDP ranks per run)
#SBATCH --ntasks-per-node=4
#SBATCH --gres=gpu:4                     # number of GPUs per node (global batch = 4 x batch_size)
#SBATCH --cpus-per-task=24               # number of CPUs per task
#SBATCH --time=04:30:00                  # maximum run time (HH:MM:SS)
#SBATCH --hint=nomultithread
#SBATCH --account=<group>@h100
#SBATCH --mail-type=ALL                  # When to send email notifications
#SBATCH --mail-user=your.email@institution.org
#SBATCH --array=0-2%3                     # 3 configs, run in parallel

# Array job: one training per array task (configs generated by gen_sweep_configs.py)

# Training ids (array task i runs TIDS[i]): 40 = LoRA rank 8, 41 = rank 4, 42 = rank 16
TIDS=(training_40 training_41 training_42)

TID="${TIDS[$SLURM_ARRAY_TASK_ID]}"
if [[ -z "$TID" ]]; then
    echo "No training_id for SLURM_ARRAY_TASK_ID=$SLURM_ARRAY_TASK_ID (TIDS has ${#TIDS[@]} entries)" >&2
    exit 1
fi
echo "=== array task $SLURM_ARRAY_TASK_ID  ->  $TID ==="

# Clean inherited modules
module purge

# Select modules compiled for H100
module load arch/h100

# Load modules
module load miniforge/24.11.3
module load cuda/12.8.0

# Deactivate inherited environments
conda deactivate

# Activate conda environment
conda activate histost_env

# Start training for this array task's config
srun /linkhome/rech/<home_group>/<login>/ST_HE/HistoST/src/training/run_experiment.py \
    --training_id "$TID"
